/**
 * Step 3 of growing the skill graph: turn reviewed proposals into RDF.
 *
 *   npm run graph:apply            # validate, write, re-tag jobs
 *   npm run graph:apply -- --check # validate only, change nothing
 *
 * Reads every batch in data/skill-proposals/ (oldest first), checks each one
 * against the graph as it stands after the previous batches, writes
 * ontology/skills-learned.rdf.ttl, SHACL-validates the whole ontology and,
 * if anything is wrong, leaves every file untouched.
 */

import { execFileSync } from 'child_process'
import * as fs from 'fs'
import * as path from 'path'
import * as N3 from 'n3'
import * as os from 'os'
import { batchToQuads, ProposalBatch, validateBatch } from '../lib/graph/proposals'
import { quadsToTurtle } from '../lib/jobs/rdf'
import { MemoryGraphStore } from '../lib/rdf/store'
import { BASE_ONTOLOGY_FILES, LEARNED_SKILLS_FILE, ONTOLOGY_DIR, readTurtleFile, validateQuads } from '../lib/rdf/shacl'

const PROPOSALS_DIR = path.join(process.cwd(), 'data', 'skill-proposals')
const LEARNED_PATH = path.join(ONTOLOGY_DIR, LEARNED_SKILLS_FILE)
const BASE_FILES = BASE_ONTOLOGY_FILES

async function main() {
  const checkOnly = process.argv.includes('--check')
  const files = fs.existsSync(PROPOSALS_DIR)
    ? fs.readdirSync(PROPOSALS_DIR).filter((f) => f.endsWith('.json')).sort()
    : []
  if (files.length === 0) throw new Error('No proposal batches in data/skill-proposals/')

  // Validate batches one after another on a scratch copy of the graph.
  const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'skillmatch-'))
  for (const f of BASE_FILES) fs.copyFileSync(path.join(ONTOLOGY_DIR, f), path.join(scratch, f))

  const learned: N3.Quad[] = []
  let added = 0
  let aliases = 0
  for (const file of files) {
    const batch: ProposalBatch = JSON.parse(fs.readFileSync(path.join(PROPOSALS_DIR, file), 'utf-8'))
    const graph = new MemoryGraphStore(scratch, [...BASE_FILES, LEARNED_SKILLS_FILE])
    fs.writeFileSync(path.join(scratch, LEARNED_SKILLS_FILE), await quadsToTurtle(learned))
    await graph.initialize()

    const issues = validateBatch(batch, await graph.getAllSkills())
    if (issues.length > 0) {
      console.error(`✗ ${file}: ${issues.length} problem(s)`)
      for (const i of issues) console.error(`   ${i.where}: ${i.message}`)
      process.exit(1)
    }
    learned.push(...batchToQuads(batch))
    added += batch.newSkills.length
    aliases += (batch.newAliases ?? []).reduce((n, a) => n + a.aliases.length, 0)
    console.log(`✓ ${file}: ${batch.newSkills.length} new skills, ${(batch.newAliases ?? []).length} alias updates, ${(batch.rejected ?? []).length} rejected`)
  }

  const report = await validateQuads([...BASE_FILES.flatMap((f) => readTurtleFile(f)), ...learned])
  if (!report.valid) {
    console.error('✗ SHACL validation failed; nothing was written:')
    for (const v of report.violations.filter((v) => v.severity === 'Violation').slice(0, 20)) {
      console.error(`   ${v.focusNode} ${v.path}: ${v.message}`)
    }
    process.exit(1)
  }
  const warnings = report.violations.filter((v) => v.severity === 'Warning')
  if (warnings.length > 0) {
    console.error(`✗ ${warnings.length} SHACL warnings (e.g. ${warnings[0].message}); nothing was written`)
    process.exit(1)
  }

  console.log(`\nAll batches valid: ${added} skills and ${aliases} aliases (SHACL valid).`)
  if (checkOnly) return

  const header =
    `# Generated by scripts/apply-skill-proposals.ts from data/skill-proposals/*.json. Do not edit by hand.\n` +
    `# ${added} skills and ${aliases} aliases proposed by automated review and validated by SHACL.\n\n`
  fs.writeFileSync(LEARNED_PATH, await quadsToTurtle(learned, header))
  console.log(`Wrote ontology/${LEARNED_SKILLS_FILE}. Re-tagging jobs with the new skills…\n`)

  if (fs.existsSync(path.join(process.cwd(), 'data', 'raw', 'jobs.json'))) {
    execFileSync('npx', ['tsx', 'scripts/fetch-jobs.ts', '--offline'], { stdio: 'inherit' })
  } else {
    console.log('No saved postings (data/raw/jobs.json); run `npm run fetch-jobs` to re-tag.')
  }
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error)
  process.exit(1)
})
